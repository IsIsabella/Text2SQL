package org.texttosql;

/**
 * Перечисление, представляющее статус совпадения двух субъектов доступа
 * на основе рассчитанной вероятности их идентичности
 */
public enum MatchStatus {
    /**
     * Полное совпадение субъектов (вероятность совпадения ≥ 90%)
     */
    MATCH("совпадают"),
    /**
     * Требуется ручная проверка (вероятность совпадения ∈ [70%, 90%))
     */
    MANUAL_VERIFICATION("требуется ручная проверка"),
    /**
     * Субъекты не совпадают (вероятность совпадения < 70%)
     */
    DIFFERENT("разные");

    /**
     * Описание статуса на русском языке
     */
    private final String description;

    /**
     * Конструктор перечисления
     *
     * @param description описание статуса для вывода
     */
    MatchStatus(String description) {
        this.description = description;
    }

    /**
     * Возвращает строковое представление статуса на русском языке
     *
     * @return описание статуса
     */
    @Override
    public String toString() {
        return description;
    }
}
